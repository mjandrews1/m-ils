#!/bin/bash
# build-carrier.sh — regenerate src/ILS.m (the mJVM single-file carrier) from the
# GT.M-side modules (ILSREC, ILSAUTH, ILSEARCH, ILSTUI).
#
# mJVM compiles ONE file, so cross-routine calls (D DEMO^ILSREC, $$FOLD^ILSAUTH)
# cannot resolve; the carrier concatenates the modules and strips the ^ROUTINE
# qualifiers so every call resolves to an in-file label. GT.M keeps the separate
# routines. Edit the modules, never the carrier; rebuild with this script.
#
# Battery runs (mJVM): a driver preamble must precede the carrier, e.g.
#   { printf ' D ILSTEST\n Q\n'; cat src/ILS.m; cat <test body>; } > run.m
# (top-level execution would otherwise fall into PUT's body and QUIT).
set -eu
D="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "ILS ; m-ils concatenated routine — all modules in one file for mJVM"
  echo " ; GENERATED by tools/build-carrier.sh from ILSREC/ILSAUTH/ILSEARCH/ILSTUI."
  echo " ; Do not edit by hand; edit the modules and rebuild."
  echo " ;"
  for m in ILSREC ILSAUTH ILSEARCH ILSMARC ILSTUI; do
    # Device syntax: GT.M uses the filename as the device (O fn:readonly);
    # mJVM wants a channel (O 20:fn). Three single-line rewrites:
    sed -e 's/^ O fn:readonly$/ O 20:fn/' -e 's/^ U fn$/ U 20/' \
        -e 's/^ C fn$/ C 20/' \
        -e 's/\^ILSREC//g' -e 's/\^ILSAUTH//g' -e 's/\^ILSEARCH//g' \
        -e 's/\^ILSMARC//g' -e 's/\^ILSTUI//g' "$D/src/$m.m"
    echo " ;"
  done
} > "$D/src/ILS.m"
echo "carrier: $D/src/ILS.m ($(grep -c '' "$D/src/ILS.m") lines)"
